"""Regenerate docs/validation.md by running every recipe on the real data.

Usage: PYNHTS_CACHE_DIR=... python tools/make_validation_report.py
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pynhts
from pynhts import recipes
from pynhts.recipes.base import load_spec

OUT = Path(__file__).resolve().parents[1] / "docs" / "validation.md"

RULE = (
    "Status rule: the estimate must match the printed figure to half a unit of its last printed "
    "digit; where a margin of error is printed, the 95 % margin of error (2017: t(0.975, 98) x JKn "
    "standard error) must match to the same rounding or 0.1 %, whichever is larger. The *MOE diff* "
    "column is (ours - published) / published. Studies that publish unweighted counts or control "
    "totals (the 2022 User Guide) have no MOE, so only the estimate decides the status. The "
    "MOE column shows our own margin of error (2022: Taylor series, t with the design df)."
)


def section(name: str, data: pynhts.NHTSData) -> tuple[list[str], dict[str, int]]:
    spec = load_spec(name)
    table = recipes.run(name, data)
    counts = {k: int(v) for k, v in table["status"].value_counts().to_dict().items()}
    lines = [
        f"## {spec.title}",
        "",
        f"**Source:** {spec.citation}",
        "",
        f"**Scorecard ({len(table)} published figures):** "
        f"{counts.get('reproduced', 0)} reproduced, "
        f"{counts.get('estimate_only', 0)} estimate reproduced but margin of error differs, "
        f"{counts.get('not_reproduced', 0)} not reproduced.",
        "",
        recipes.to_markdown(table),
        "### Known gaps",
        "",
    ]
    for t in spec.targets:
        if t.expected != "reproduced":
            lines += [f"* **{t.label}** (`{t.id}`, Table {t.table}, status `{t.expected}`): "
                      f"{t.note}", ""]
    return lines, counts


def main() -> None:
    waves = {w: pynhts.load(w, offline=True, replicates=True) for w in (2017, 2022)}
    lines = [
        "# Validation against published NHTS results (2017 and 2022)",
        "",
        f"*Generated by `tools/make_validation_report.py` on {date.today().isoformat()} with "
        f"pynhts {pynhts.__version__}. Do not edit by hand.*",
        "",
        RULE,
        "",
    ]
    summary = {}
    for name in recipes.available():
        body, counts = section(name, waves[load_spec(name).wave])
        lines += body + [""]
        summary[name] = counts
    lines += [
        "These gaps are reported, not tuned away: no rule in the library was changed to make a "
        "figure match. If you can explain one, please open an issue.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} {summary}")


if __name__ == "__main__":
    main()
