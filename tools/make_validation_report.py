"""Regenerate docs/validation.md by running every recipe on the real data.

Usage: PYNHTS_CACHE_DIR=... python tools/make_validation_report.py
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pynhts
from pynhts import recipes
from pynhts.recipes.base import load_spec

OUT = Path(__file__).resolve().parents[1] / "docs" / "validation.md"


def main() -> None:
    data = pynhts.load(2017, offline=True, replicates=True)
    spec = load_spec("stt2017")
    table = recipes.run("stt2017", data)
    counts = table["status"].value_counts().to_dict()
    lines = [
        "# Validation against published NHTS 2017 tables",
        "",
        f"*Generated by `tools/make_validation_report.py` on {date.today().isoformat()} with "
        f"pynhts {pynhts.__version__}. Do not edit by hand.*",
        "",
        f"**Source:** {spec.citation}",
        "",
        f"**Scorecard ({len(table)} published figures):** "
        f"{counts.get('reproduced', 0)} reproduced, "
        f"{counts.get('estimate_only', 0)} estimate reproduced but margin of error differs, "
        f"{counts.get('not_reproduced', 0)} not reproduced.",
        "",
        "Status rule: the estimate must match the printed figure to half a unit of its last "
        "printed digit; the 95 % margin of error (MOE = t(0.975, 98) x JKn standard error) must "
        "match to the same rounding or 0.1 %, whichever is larger. Figures are in the report's "
        "units (thousands for Table 1, daily rates for Table 3). The *MOE diff* column is "
        "(ours - published) / published.",
        "",
        recipes.to_markdown(table),
        "## Known gaps",
        "",
    ]
    for t in spec.targets:
        if t.expected != "reproduced":
            lines += [f"* **{t.label}** (`{t.id}`, Table {t.table}, status `{t.expected}`): "
                      f"{t.note}", ""]
    lines += [
        "These gaps are reported, not tuned away: no rule in the library was changed to make "
        "a figure match. If you can explain one, please open an issue.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({counts})")


if __name__ == "__main__":
    main()
